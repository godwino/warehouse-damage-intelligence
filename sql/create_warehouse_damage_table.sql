/*
    Warehouse Damage Intelligence
    SQL Server table creation script for the synthetic warehouse damage dataset.

    This script:
    1. Drops the table if it already exists
    2. Recreates the warehouse_damage table with column names that match the CSV exactly
    3. Includes import guidance for SQL Server
*/

-- Drop the existing table so the structure can be recreated cleanly.
DROP TABLE IF EXISTS warehouse_damage;
GO

-- Create a table that matches the generated CSV file exactly.
CREATE TABLE warehouse_damage (
    [date] DATE NOT NULL,
    sku VARCHAR(50) NOT NULL,
    [description] VARCHAR(200) NOT NULL,
    category VARCHAR(50) NOT NULL,
    aisle VARCHAR(20) NOT NULL,
    slot_level VARCHAR(30) NOT NULL,
    shift VARCHAR(30) NOT NULL,
    process_area VARCHAR(50) NOT NULL,
    damage_source VARCHAR(100) NOT NULL,
    equipment_type VARCHAR(50) NOT NULL,
    handling_stage VARCHAR(50) NOT NULL,
    congestion_level VARCHAR(20) NOT NULL,
    pallet_stability VARCHAR(30) NOT NULL,
    equipment_condition VARCHAR(30) NOT NULL,
    slotting_risk VARCHAR(20) NOT NULL,
    cases_handled INT NOT NULL,
    damaged_cases INT NOT NULL,
    damage_type VARCHAR(50) NOT NULL,
    weight_lbs DECIMAL(10, 2) NOT NULL,
    cube DECIMAL(10, 2) NOT NULL,
    cost_per_case DECIMAL(10, 2) NOT NULL,
    damage_rate DECIMAL(10, 4) NOT NULL,
    damage_cost DECIMAL(12, 2) NOT NULL,
    high_damage INT NOT NULL
);
GO

